// Where the explanatory prose lives.  The methodology used to be spread across
// wordy disclaimers under individual charts; it is now one collapsed block in
// the footer.  Both halves of that are worth pinning: the block says the right
// things, and the charts have stopped repeating them.
const {load, suite} = require("./page.js");

const VIEWS = ["archive", "time", "breakdown", "table", "lists"];

// Prose that belongs in the footer and must not reappear under a chart.
const MOVED = [
  /stop where the series left archive\.ubuntu\.com/,
  /are read from archive\.ubuntu\.com/,
  /Archive size tab counts each file once/,
  /counted only up to the point they left/,
];

suite(async ({page, check}) => {
  const T = await load(page);
  const f = T.S.document.getElementById("footer").innerHTML;

  check("footer has a details block", /<details>/.test(f), true);
  check("collapsed by default (no open attribute)",
        /<details(\s|>)/.test(f) && !/<details[^>]*\bopen\b/.test(f), true);
  check("summary wording", /<summary>([^<]+)<\/summary>/.exec(f)[1],
        "How these numbers are counted");
  check("seven paragraphs inside", (f.match(/<p>/g) || []).length, 7);
  check("dash convention is explained there",
        /each repeat is dashed/.test(f), true);
  check("attribution sits outside the details",
        /<\/details>Generated by /.test(f), true);
  check("provenance moved in: removed series",
        /left archive\.ubuntu\.com/.test(f), true);
  check("provenance moved in: live series",
        /read from archive\.ubuntu\.com/.test(f), true);
  check("names the removal dates", /kinetic \(\d{4}-\d{2}-\d{2}\)/.test(f), true);

  // The long disclaimers must be gone from under every chart, on every tab.
  for (const v of VIEWS) {
    T.state.view = v;
    for (const split of ["series", "arch"]) {
      T.state.splitBy = split;
      T.render();
      const body = T.S.document.getElementById("views").textContent;
      for (const re of MOVED) {
        check("no chart prose " + re.source.slice(0, 22)
              + " on " + v + "/" + split, re.test(body), false);
      }
    }
  }

  // Hue reuse must say nothing under the chart, however many lines are up.
  // Every series against 8 hues forces several repeats, which is what used to
  // trigger the note; the legend carries the colour-and-dash pairing instead.
  T.state.view = "time";
  T.state.splitBy = "series";
  T.state.series.clear();
  T.D.series.forEach((_, i) => T.state.series.add(i));
  T.render();
  const many = T.S.document.getElementById("views").textContent;
  check("no colour note with every series",
        /reuse a hue|lines are selected/.test(many), false);
  check("no undrawn-lines note", /not drawn|worth reporting/.test(many), false);
  check("the chart still drew", many.length > 200, true);
  T.resetDefaults();

  // The useful inline notes must survive: these read the chart in front of
  // you rather than restating the methodology.
  T.state.view = "archive";
  T.state.splitBy = "series";
  T.render();
  const arch = T.S.document.getElementById("views").textContent;
  check("archive size keeps its summary line",
        /and kernels went from [\d.]+% of it to [\d.]+%\./.test(arch), true);

  // The 'all' note is conditional on the arch split with 'all' ticked.
  T.state.view = "lists";
  T.state.splitBy = "arch";
  T.render();
  const lists = T.S.document.getElementById("views").textContent;
  check("package lists keeps its summary line",
        /index files at \d{4}-\d{2}-\d{2} holding/.test(lists), true);
  check("package lists keeps the 'all' explanation",
        /'all' has no line because it has no index directory/.test(lists), true);
});
